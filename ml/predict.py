"""
============================================================
A²FaaS
ML Risk Prediction Service
============================================================

Loads the trained UNSW-NB15 Logistic Regression pipeline
and converts incoming network traffic features into an
attack probability and firewall risk level.

Model classes:
    0 = Normal traffic
    1 = Attack traffic

Risk levels:
    NORMAL prediction             -> LOW
    ATTACK + probability < 0.90  -> MEDIUM
    ATTACK + probability >= 0.90 -> HIGH

The trained model is generated by:
    ml/train_model.py

Model artifact:
    ml/a2faas_risk_model.joblib
============================================================
"""

from pathlib import Path
from typing import Any

import joblib
import pandas as pd


# ============================================================
# PATH CONFIGURATION
# ============================================================

ML_DIRECTORY = Path(__file__).resolve().parent

MODEL_PATH = ML_DIRECTORY / "a2faas_risk_model.joblib"


# ============================================================
# MODEL CACHE
# ============================================================

_model = None


# ============================================================
# MODEL LOADING
# ============================================================

def load_model():
    """
    Load the trained A²FaaS ML pipeline.

    The model is loaded only once and then reused for
    subsequent predictions.
    """

    global _model

    if _model is None:

        if not MODEL_PATH.exists():
            raise FileNotFoundError(
                f"Trained model not found: {MODEL_PATH}"
            )

        _model = joblib.load(MODEL_PATH)

    return _model


# ============================================================
# RISK CLASSIFICATION
# ============================================================

def classify_risk(
    risk_score: float,
    prediction: int,
) -> str:
    """
    Convert the trained model's prediction and attack
    probability into a firewall risk level.

    The model's predicted class is the primary signal.

    Parameters
    ----------
    risk_score:
        Probability of attack traffic.

    prediction:
        Model classification:
            0 = Normal
            1 = Attack

    Returns
    -------
    str
        LOW, MEDIUM, or HIGH
    """

    # --------------------------------------------------------
    # NORMAL TRAFFIC
    # --------------------------------------------------------

    if prediction == 0:
        return "LOW"

    # --------------------------------------------------------
    # ATTACK TRAFFIC
    # --------------------------------------------------------

    if risk_score >= 0.90:
        return "HIGH"

    return "MEDIUM"


# ============================================================
# RISK PREDICTION
# ============================================================

def predict_risk(
    features: dict[str, Any],
) -> dict[str, Any]:
    """
    Predict whether incoming traffic represents normal
    or attack activity.

    Parameters
    ----------
    features:
        Dictionary containing UNSW-NB15-compatible feature
        names and values.

    Returns
    -------
    dict
        Contains:

        risk_score
            Exact probability of attack traffic.

        risk_level
            LOW, MEDIUM, or HIGH.

        prediction
            0 = Normal
            1 = Attack.
    """

    # --------------------------------------------------------
    # Load trained pipeline
    # --------------------------------------------------------

    model = load_model()

    # --------------------------------------------------------
    # Convert feature dictionary into one-row DataFrame
    # --------------------------------------------------------

    input_frame = pd.DataFrame(
        [features]
    )

    # --------------------------------------------------------
    # Generate class probabilities
    # --------------------------------------------------------

    probabilities = model.predict_proba(
        input_frame
    )

    # --------------------------------------------------------
    # UNSW-NB15 target:
    #
    # 0 = Normal
    # 1 = Attack
    #
    # Therefore probabilities[0][1] represents the
    # probability of attack traffic.
    # --------------------------------------------------------

    attack_probability = float(
        probabilities[0][1]
    )

    # --------------------------------------------------------
    # Keep probability safely within [0, 1]
    # --------------------------------------------------------

    attack_probability = max(
        0.0,
        min(
            1.0,
            attack_probability,
        ),
    )

    # --------------------------------------------------------
    # Generate actual model prediction
    # --------------------------------------------------------

    prediction = int(
        model.predict(
            input_frame
        )[0]
    )

    # --------------------------------------------------------
    # Convert model output into firewall risk level
    # --------------------------------------------------------

    risk_level = classify_risk(
        risk_score=attack_probability,
        prediction=prediction,
    )

    # --------------------------------------------------------
    # Return exact probability
    #
    # Do NOT round the probability.
    #
    # Very small probabilities are meaningful and should not
    # be converted into an artificial 0.0.
    # --------------------------------------------------------

    return {
        "risk_score": attack_probability,
        "risk_level": risk_level,
        "prediction": prediction,
    }


# ============================================================
# MODEL INFORMATION
# ============================================================

def get_model_information() -> dict[str, Any]:
    """
    Return information about the currently loaded ML model.
    """

    model = load_model()

    return {
        "model_available": True,
        "model_type": type(model).__name__,
        "model_path": str(MODEL_PATH),
    }


